// Общий записанный ответ, если ни один шаблон не подошёл.
export function genericResponse(answers) {
  const complaint = (answers.complaint || 'жалобы не уточнены').trim();
  return {
    complaints: complaint.charAt(0).toUpperCase() + complaint.slice(1),
    draft:
      `Пациент обратился с жалобами: ${complaint}. ` +
      `Длительность: ${answers.duration || 'не уточнена'}. ` +
      `Интенсивность боли по десятибалльной шкале: ${answers.pain || 'не указана'}. ` +
      `Аллергологический анамнез: ${answers.allergies || 'не уточнён'}. ` +
      `Хронические заболевания: ${answers.chronic || 'не уточнены'}. ` +
      `Принимаемые препараты: ${answers.meds || 'не уточнены'}. ` +
      `Рекомендован осмотр врача в порядке, соответствующем присвоенной категории срочности.`,
  };
}

export function playback(answers) {
  const hay = [answers.complaint, answers.redflags].join(' ');
  const hit = FIXTURES.find((f) => f.match.test(hay));
  return hit ? { ...hit.response } : genericResponse(answers);
}
